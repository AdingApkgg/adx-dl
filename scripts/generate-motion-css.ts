import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { motionPresets as p } from "../packages/ui/src/motion/presets";
import { motionTokens as t } from "../packages/ui/src/motion/tokens";

const values: Record<string, string | number> = {};
for (const [name, ms] of Object.entries(t.duration)) values[`duration-${name}`] = `${ms}ms`;
for (const [name, px] of Object.entries(t.distance)) values[`distance-${name}`] = `${px}px`;
values["scale-press"] = t.scale.press;
values["scale-dialog-start"] = t.scale.dialogStart;
for (const [name, curve] of Object.entries(t.easing)) values[`easing-${name}`] = `cubic-bezier(${curve.join(", ")})`;
for (const [name, ms] of Object.entries({ popup: t.duration.fast, backdrop: t.duration.default, dialog: t.duration.default, sheet: t.duration.default, page: p.page.enter.durationMs })) {
  values[`${name}-enter-duration`] = `${ms}ms`;
  values[`${name}-exit-duration`] = `${name === "page" ? p.page.exit.durationMs : t.duration.fast}ms`;
}
values["page-enter-distance"] = `${p.page.enter.distancePx}px`;
values["page-exit-distance"] = `${p.page.exit.distancePx}px`;
values["ambient-disc-duration"] = `${p.ambient.loop.discDurationMs}ms`;
values["ambient-equalizer-duration"] = `${p.ambient.loop.equalizerDurationMs}ms`;
values["ambient-sweep-duration"] = `${p.ambient.loop.sweepDurationMs + p.ambient.loop.sweepDelayMs}ms`;
values["shared-move-duration"] = `${p.shared.move.durationMs}ms`;
const sweepEnd = (100 * p.ambient.loop.sweepDurationMs / (p.ambient.loop.sweepDurationMs + p.ambient.loop.sweepDelayMs)).toFixed(3);
const css = `/* Generated by scripts/generate-motion-css.ts. Do not edit by hand. */\n:root {\n${Object.entries(values).map(([key, value]) => `  --adx-motion-${key}: ${value};`).join("\n")}\n}\n@keyframes adx-ambient-download-sweep {\n  0% { transform: translateX(-110%); }\n  ${sweepEnd}%, 100% { transform: translateX(320%); }\n}\n`;
const path = fileURLToPath(new URL("../packages/ui/src/styles/motion-tokens.css", import.meta.url));
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== css) throw new Error("Motion CSS is stale. Run: bun scripts/generate-motion-css.ts");
} else {
  writeFileSync(path, css);
}
